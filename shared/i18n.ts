const DICTS: Record<Lang, Dict> = { tr, en };

export function t(lang: Lang, key: keyof typeof tr, params?: Record<string, string | number>): string {
  const text = DICTS[lang]?.[key] ?? DICTS.tr[key] ?? key;
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (_, p) => String(params[p] ?? `{${p}}`));
}

export const localeOf = (lang: Lang) => (lang === "en" ? "en-GB" : "tr-TR");
